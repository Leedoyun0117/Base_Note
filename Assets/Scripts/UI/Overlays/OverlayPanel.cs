namespace GameName.UI.Overlays
{
    // 플레이 화면 위에 전체를 덮고 뜨는 오버레이 화면의 종류.
    //
    // 지금은 기록지와 인벤토리 둘뿐이고 각자 다른 키(Tab / I)로 열리지만,
    // 나중에 이 둘을 하나의 컨테이너 안 탭으로 합칠 예정이다. 그때 바뀌는 것은
    // "어떤 입력이 어떤 값을 고르는가"와 컨테이너의 생김새뿐이고, 이 열거형과
    // OverlayPanelRouter는 그대로 남는다 — 탭이란 결국 "한 번에 하나만 보인다"는
    // 규칙이고, 그 규칙은 이미 라우터가 지키고 있기 때문이다.
    public enum OverlayPanel
    {
        Journal,
        Inventory,

        // 단서를 눌렀을 때 뜨는 확대 화면. 키로 여는 것이 아니라 씬에서
        // 열리지만, 화면 전체를 덮는다는 점은 나머지와 똑같다 — 가시성을 여기
        // 함께 두면 "확대 화면을 보는 중에 기록지가 겹쳐 뜬다" 같은 조합을
        // 라우터가 알아서 막아 준다.
        ClueZoom
    }
}
