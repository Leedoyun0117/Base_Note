namespace GameName.UI.MemoryRoom.Space
{
    // 마우스로 가리키고 누를 수 있는 씬 오브젝트의 최소 계약.
    //
    // 입력을 읽는 곳(ScenePointerInput)이 단서인지 출입구인지 구분하지 않고
    // 똑같이 다룰 수 있게 하기 위한 것이다. 그래야 입력 처리 코드가 오브젝트
    // 종류만큼 늘어나지 않는다.
    public interface IPointerInteractable
    {
        // 이 오브젝트가 얼마나 앞에 그려지는가(스프라이트 정렬 순서).
        //
        // 판정 영역이 겹쳤을 때 누구를 가리킨 것으로 볼지 정하는 데 쓴다. 화면에
        // 앞에 보이는 것을 누른 것으로 치는 게 사람이 기대하는 동작이고, 그
        // "앞"의 유일한 진실은 그리는 순서다. 입력을 읽는 쪽이 오브젝트 종류를
        // 알아내 우선순위를 매기면(단서가 출입구보다 위, 같은 규칙이 두 곳에
        // 생긴다) 종류가 늘 때마다 그 표가 함께 늘어난다.
        int DrawOrder { get; }

        // 마우스가 올라왔는지 여부. 강조 표시를 켜고 끄는 데 쓴다.
        void SetHovered(bool hovered);

        // 눌렸다. 무엇을 할지는 각 오브젝트가 자기 이벤트로 알린다.
        void Activate();
    }
}
