namespace GameName.Core.Trust
{
    // 신뢰도를 실제로 움직일 수 있는 경계.
    // 선택지 처리기처럼 신뢰도를 깎을 자격이 있는 쪽에만 주입한다.
    //
    // 감소만 두는 이유: 이 게임에서 신뢰도는 오르지 않는다. 방에 들어설 때 정해진
    // 값에서 시작해 오답으로만 깎이고, 0에 닿으면 방이 실패로 닫힌다. 올리는 경로가
    // 아예 없으므로 증가 연산을 두면 "언젠가 쓸지도 모르는" 문을 열어 두는 셈이다.
    //
    // 얼마나 깎을지는 인자로 받되, 게이지 자신은 "무엇 때문에" 깎이는지 모른다 —
    // 오답 한 번에 얼마를 깎을지는 대화 진행 규칙(DialogueProgressor)의 판단이고,
    // 게이지는 0 하한 처리와 변화 이벤트 발행만 책임진다.
    public interface ITrustGauge : ITrustReader
    {
        void Decrease(int amount);
    }
}
