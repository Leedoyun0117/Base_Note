namespace GameName.Core.Clues
{
    // 태그가 그 소유자(단서 하나 또는 질문 한 줄)에서 차지하는 축.
    //
    // Center: 그 단서·질문이 "정말로 무엇에 대한 것인가" — 이 개편에서는 감정
    //         축이다. 질문의 중심축과 답의 중심축이 맞을 때만 완전한 정답이 된다.
    // Sub:    곁으로 걸치는 축(장소·시간 등). 중심 감정은 어긋났지만 스치기는
    //         한 답이라, 등급 판정기가 부분 적합으로 친다.
    //
    // 이 값은 태그의 정체성이 아니다. 같은 말을 가리키는 태그는 한 단서에서
    // 중심축, 다른 단서에서 곁축일 수 있다(질문마다 중심 감정이 다르므로).
    // 그래서 ClueTag의 동치 비교는 Axis를 보지 않고 Value로만 하고, Axis는
    // 등급 판정기만 들여다본다.
    public enum ClueTagAxis
    {
        Center,
        Sub
    }
}
