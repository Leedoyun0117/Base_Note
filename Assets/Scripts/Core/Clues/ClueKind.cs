namespace GameName.Core.Clues
{
    // 단서가 방 안에서 어디에 놓이는 물건인지를 나타내는 종류.
    //
    // "겉보기 구성"과 달리 이것은 감출 이유가 전혀 없는 정보다 — 방에 들어서면
    // 눈으로 바로 보이는 사실이기 때문이다. 그래서 ClueDefinition뿐 아니라
    // ClueInfo에도 그대로 실려 화면까지 전달된다.
    //
    // 규칙상 이 값이 필요한 이유는 하나다: 단서를 버릴 때 포스터는 벽에,
    // 물건은 바닥에 놓여야 하므로 "어느 높이에 놓이는가"를 데이터로 구분할 수
    // 있어야 한다. 그 높이 계산 자체는 표시 계층(CluePlacementLayout)의 몫이고,
    // Core는 종류만 들고 있는다.
    public enum ClueKind
    {
        // 벽에 붙는 단서(포스터, 사진, 액자 등).
        Poster,

        // 바닥에 떨어져 있는 단서(반지, 편지, 일기장 등).
        FloorObject
    }
}
