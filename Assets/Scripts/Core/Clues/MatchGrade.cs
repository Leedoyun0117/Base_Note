namespace GameName.Core.Clues
{
    // 질문에 낸 답(단서)이 얼마나 맞는지 — 이진 정답/오답을 대체하는 5단계.
    //
    // 이진 판정을 타입으로 못박는 이유는 MemoryColor·PsychologyState와 같다:
    // 단계가 늘거나 줄면 피드백 대사·안정 축 이동·회복량 계산이 함께 바뀌므로
    // 밸런싱 수치로 흘려보낼 값이 아니다.
    //
    // 나쁜 쪽에서 좋은 쪽 순서다 — 심리 × 안정 조합이 등급을 밀어 올리거나
    // 내릴 수 있어([10]) 서수 비교가 의미를 갖는다.
    public enum MatchGrade
    {
        // 무관 — 겹치는 태그가 없다.
        None,

        // 낮음 — 곁축(장소·시간)끼리만 스친다.
        Low,

        // 부분 — 중심축은 어긋났지만 축이 엇갈려 걸친다(답의 중심축이 질문의
        // 곁축, 또는 그 반대).
        Partial,

        // 높음 — 중심축(감정)이 맞지만 질문이 요구한 곁축을 다 덮지는 못한다.
        High,

        // 완전적합 — 중심축이 맞고, 질문이 요구한 곁축을 답이 전부 덮는다.
        Exact
    }
}
