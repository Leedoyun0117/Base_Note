namespace GameName.Core.Dialogue
{
    // 선택지를 화면에 내보일지 정하는 조건의 종류.
    //
    // 조건을 하나의 자유로운 식(스크립트, 람다)으로 두지 않고 종류로 못박은
    // 이유: 이 값들은 저작 데이터라 인스펙터에서 골라야 하고, 검증기가 저작
    // 시점에 "이 조건이 영영 참이 될 수 없는가"를 판단할 수 있어야 한다.
    // 임의의 식은 둘 다 불가능하게 만든다.
    public enum ChoiceConditionKind
    {
        // 항상 보인다.
        None,

        // 특정 단서를 대화에 이미 사용했어야 보인다.
        //
        // 단서를 대화에 꺼내 쓰는 것과 그 단서를 추출해 사실을 알아내는 것은
        // 서로 다른 행동이고(ClueState가 둘을 나눠 두는 이유가 그것이다), 어느
        // 쪽을 거쳤는지에 따라 열려야 할 말이 다르다.
        ClueUsed
    }
}
