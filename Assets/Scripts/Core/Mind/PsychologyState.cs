namespace GameName.Core.Mind
{
    // 나츠가 지금 기억을 어떤 방식으로 해석하는가 — 같은 단서라도 이 상태에
    // 따라 끌어내는 의미가 달라진다(같은 기억의 효과가 안정 축과의 조합에서
    // 역전될 수 있다는 규칙이 여기서 나온다).
    //
    // MemoryColor와 같은 이유로 데이터가 아니라 타입으로 못박는다: 상태가
    // 늘거나 줄면 해석 규칙(심리 × 안정 조합)과 화면 표현이 함께 바뀌므로,
    // 밸런싱 수치처럼 데이터로 흘려보낼 값이 아니다.
    public enum PsychologyState
    {
        // 낙관 — 기억을 유리한 쪽으로 읽는다.
        Optimism,

        // 광기 — 기억을 과장하거나 뒤집어 읽는다.
        Mania,

        // 우울 — 기억을 가라앉은 쪽으로 읽는다.
        Melancholy
    }
}
